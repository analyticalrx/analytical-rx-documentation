do $$
declare
  application_role text;
begin
  foreach application_role in array array[
    'analyticalrx_app_rw',
    'analyticalrx_data_platform_password_rw'
  ] loop
    if exists (select 1 from pg_roles where rolname = application_role) then
      execute format('grant usage on schema control_plane to %I', application_role);
      execute format(
        'grant select, insert, update, delete on all tables in schema control_plane to %I',
        application_role
      );
      execute format(
        'grant usage, select on all sequences in schema control_plane to %I',
        application_role
      );
      execute format(
        'alter default privileges in schema control_plane grant select, insert, update, delete on tables to %I',
        application_role
      );
      execute format(
        'alter default privileges in schema control_plane grant usage, select on sequences to %I',
        application_role
      );
    end if;
  end loop;
end $$;
