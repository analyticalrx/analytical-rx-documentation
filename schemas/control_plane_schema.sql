-- AnalyticalRx Phase 1 control-plane schema.
-- Target database: PostgreSQL-compatible engine such as AWS RDS PostgreSQL or Aurora PostgreSQL.
-- Purpose: shared non-PHI metadata for login, tenant routing, role-based access, and application audit.
--
-- Tenant-owned pharmacy/event data belongs in tenant schemas such as tenant_analyticalrx_dev.
-- The tenant_registry ID and matching tenant-schema tenant ID use the same bigint value.

create schema if not exists control_plane;
set search_path to control_plane, public;

create table if not exists tenant_registry (
  id bigint generated by default as identity primary key,
  tenant_key text not null,
  display_name text not null,
  schema_name text not null,
  status text not null default 'active' check (status in ('onboarding', 'active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_key),
  unique (schema_name),
  check (tenant_key ~ '^[a-z0-9][a-z0-9-]*[a-z0-9]$'),
  check (schema_name ~ '^tenant_[a-z0-9_]+$')
);

create table if not exists app_user (
  id bigint generated always as identity primary key,
  tenant_id bigint not null references tenant_registry(id),
  display_name text not null,
  email text not null,
  password_hash text not null,
  password_algorithm text not null default 'bcrypt',
  phone_number text,
  job_title text,
  status text not null default 'active' check (status in ('invited', 'active', 'inactive', 'password_reset_required')),
  permissions_version integer not null default 1 check (permissions_version > 0),
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, tenant_id)
);

create unique index if not exists uq_app_user_tenant_email_lower
  on app_user (tenant_id, lower(email));

create table if not exists user_pharmacy_access (
  id bigint generated always as identity primary key,
  user_id bigint not null,
  tenant_id bigint not null,
  pharmacy_key text not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (user_id, tenant_id) references app_user(id, tenant_id) on delete cascade,
  unique (user_id, tenant_id, pharmacy_key)
);

create table if not exists role_definition (
  id bigint generated by default as identity primary key,
  role_code text not null unique,
  display_name text not null,
  description text not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists permission_definition (
  id bigint generated by default as identity primary key,
  permission_code text not null unique,
  display_name text not null,
  description text not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists role_permission (
  role_id bigint not null references role_definition(id) on delete cascade,
  permission_id bigint not null references permission_definition(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (role_id, permission_id)
);

create table if not exists user_role (
  user_id bigint not null references app_user(id) on delete cascade,
  role_id bigint not null references role_definition(id),
  status text not null default 'active' check (status in ('active', 'inactive')),
  assigned_by_user_id bigint references app_user(id),
  assigned_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, role_id)
);

create table if not exists permission_audit_event (
  id bigint generated always as identity primary key,
  actor_user_id bigint references app_user(id),
  target_user_id bigint references app_user(id),
  tenant_id bigint references tenant_registry(id),
  action text not null,
  resource_type text,
  resource_id text,
  old_value jsonb,
  new_value jsonb,
  reason text,
  request_id text,
  created_at timestamptz not null default now()
);

create table if not exists app_access_audit_event (
  id bigint generated always as identity primary key,
  user_id bigint references app_user(id),
  tenant_id bigint references tenant_registry(id),
  event_type text not null check (event_type in ('login_success', 'login_failed', 'logout', 'token_issued', 'token_rejected', 'password_changed', 'sensitive_read_denied', 'admin_action')),
  resource_type text,
  resource_id text,
  status text not null default 'success' check (status in ('success', 'failure', 'denied')),
  request_id text,
  ip_address_hash text,
  user_agent_hash text,
  details jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_tenant_registry_status on tenant_registry (status);
create index if not exists idx_app_user_tenant_status on app_user (tenant_id, status);
create index if not exists idx_user_pharmacy_access_user on user_pharmacy_access (user_id, status);
create index if not exists idx_user_role_user on user_role (user_id, status);
create index if not exists idx_role_permission_permission on role_permission (permission_id);
create index if not exists idx_permission_audit_tenant_created on permission_audit_event (tenant_id, created_at);
create index if not exists idx_app_access_audit_user_created on app_access_audit_event (user_id, created_at);

