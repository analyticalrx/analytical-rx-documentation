-- Run with psql -v ON_ERROR_STOP=1 -v dry_run=on|off -f this-file.sql.
-- Targets the current Phase 1 dev schemas only. All work is transactional.
-- Pause application/processor writers before running with dry_run=off.

begin;
set local lock_timeout = '15s';
set local statement_timeout = '5min';

do $$
declare
  schema_name text;
  tenant_count bigint;
begin
  foreach schema_name in array array['control_plane', 'tenant_analyticalrx_dev'] loop
    if to_regnamespace(schema_name) is null then
      raise exception 'Required schema % does not exist', schema_name;
    end if;
  end loop;

  select count(*) into tenant_count
  from tenant_analyticalrx_dev.tenant t
  full join control_plane.tenant_registry r using (tenant_key)
  where t.id is null or r.id is null;
  if tenant_count <> 0 then
    raise exception 'Tenant rows do not match control_plane.tenant_registry by tenant_key';
  end if;
end
$$;

create temp table migration_counts (
  schema_name text not null,
  table_name text not null,
  row_count bigint not null
) on commit drop;

create temp table migration_columns on commit drop as
select n.nspname as schema_name,
       c.relname as table_name,
       a.attname as column_name,
       a.attnotnull as was_not_null,
       a.attname = 'id' as is_row_id,
       format_type(a.atttypid, a.atttypmod) as old_type
from pg_attribute a
join pg_class c on c.oid = a.attrelid
join pg_namespace n on n.oid = c.relnamespace
where n.nspname in ('control_plane', 'tenant_analyticalrx_dev')
  and c.relkind in ('r', 'p')
  and a.attnum > 0 and not a.attisdropped
  and a.atttypid in ('uuid'::regtype, 'smallint'::regtype)
  and (
    a.attname = 'id'
    or exists (
      select 1 from pg_constraint fk
      where fk.conrelid = c.oid and fk.contype = 'f' and a.attnum = any(fk.conkey)
    )
  );

create temp table migration_constraints on commit drop as
select n.nspname as schema_name,
       c.relname as table_name,
       con.conname as constraint_name,
       con.contype as constraint_type,
       pg_get_constraintdef(con.oid) as definition
from pg_constraint con
join pg_class c on c.oid = con.conrelid
join pg_namespace n on n.oid = c.relnamespace
where n.nspname in ('control_plane', 'tenant_analyticalrx_dev')
  and c.relkind in ('r', 'p')
  and con.contype in ('p', 'u', 'f', 'c');

create temp table migration_indexes on commit drop as
select n.nspname as schema_name,
       idx.relname as index_name,
       pg_get_indexdef(idx.oid) as definition
from pg_index i
join pg_class tbl on tbl.oid = i.indrelid
join pg_namespace n on n.oid = tbl.relnamespace
join pg_class idx on idx.oid = i.indexrelid
where n.nspname in ('control_plane', 'tenant_analyticalrx_dev')
  and not exists (select 1 from pg_constraint con where con.conindid = idx.oid);

do $$
declare
  rec record;
  reference_schema text;
  reference_table text;
  reference_column text;
  reference_count integer;
  expected_count bigint;
  actual_count bigint;
  sequence_name text;
  max_id bigint;
begin
  for rec in
    select n.nspname as schema_name, c.relname as table_name
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname in ('control_plane', 'tenant_analyticalrx_dev')
      and c.relkind in ('r', 'p')
    order by n.nspname, c.relname
  loop
    execute format('lock table %I.%I in access exclusive mode', rec.schema_name, rec.table_name);
    execute format('select count(*) from %I.%I', rec.schema_name, rec.table_name)
      into expected_count;
    insert into migration_counts values (rec.schema_name, rec.table_name, expected_count);
  end loop;

  -- Identity columns populate existing rows; their old UUID/smallint values
  -- remain available to translate every child reference.
  for rec in select * from migration_columns where is_row_id order by schema_name, table_name loop
    execute format('alter table %I.%I add column id_bigint bigint generated by default as identity',
                   rec.schema_name, rec.table_name);
  end loop;

  -- The tenant row in each tenant schema uses the same ID as its registry row.
  update tenant_analyticalrx_dev.tenant t
  set id_bigint = r.id_bigint
  from control_plane.tenant_registry r
  where t.tenant_key = r.tenant_key;

  for rec in select * from migration_columns where not is_row_id order by schema_name, table_name, column_name loop
    execute format('alter table %I.%I add column %I bigint',
                   rec.schema_name, rec.table_name, rec.column_name || '_bigint');

    if rec.column_name = 'tenant_id' then
      reference_schema := rec.schema_name;
      reference_table := case when rec.schema_name = 'control_plane'
                              then 'tenant_registry' else 'tenant' end;
      reference_column := 'id';
    else
      select count(*), min(pn.nspname), min(pc.relname), min(pa.attname)
      into reference_count, reference_schema, reference_table, reference_column
      from pg_constraint fk
      join pg_class cc on cc.oid = fk.conrelid
      join pg_namespace cn on cn.oid = cc.relnamespace
      join pg_attribute ca on ca.attrelid = cc.oid
                            and ca.attnum = any(fk.conkey)
      join pg_class pc on pc.oid = fk.confrelid
      join pg_namespace pn on pn.oid = pc.relnamespace
      join pg_attribute pa on pa.attrelid = pc.oid
                            and pa.attnum = fk.confkey[array_position(fk.conkey, ca.attnum)]
      where fk.contype = 'f'
        and cn.nspname = rec.schema_name
        and cc.relname = rec.table_name
        and ca.attname = rec.column_name;
      if reference_count <> 1 or reference_column <> 'id' then
        raise exception 'Expected one parent ID for %.%.%, found %',
          rec.schema_name, rec.table_name, rec.column_name, reference_count;
      end if;
    end if;

    execute format(
      'update %I.%I child set %I = parent.id_bigint from %I.%I parent where child.%I = parent.%I',
      rec.schema_name, rec.table_name, rec.column_name || '_bigint',
      reference_schema, reference_table, rec.column_name, reference_column);

    if rec.was_not_null then
      execute format('alter table %I.%I alter column %I set not null',
                     rec.schema_name, rec.table_name, rec.column_name || '_bigint');
    end if;

    execute format('select count(*) from %I.%I where %I is not null and %I is null',
                   rec.schema_name, rec.table_name, rec.column_name,
                   rec.column_name || '_bigint') into actual_count;
    if actual_count <> 0 then
      raise exception 'Unmapped IDs in %.%.%', rec.schema_name, rec.table_name, rec.column_name;
    end if;
  end loop;

  -- Free names and dependencies before replacing column names.
  for rec in select * from migration_indexes loop
    execute format('drop index %I.%I', rec.schema_name, rec.index_name);
  end loop;
  for rec in select * from migration_constraints where constraint_type = 'f' loop
    execute format('alter table %I.%I drop constraint %I',
                   rec.schema_name, rec.table_name, rec.constraint_name);
  end loop;
  for rec in select * from migration_constraints where constraint_type <> 'f' loop
    execute format('alter table %I.%I drop constraint %I',
                   rec.schema_name, rec.table_name, rec.constraint_name);
  end loop;

  for rec in select * from migration_columns order by schema_name, table_name, column_name loop
    execute format('alter table %I.%I rename column %I to %I',
                   rec.schema_name, rec.table_name, rec.column_name,
                   rec.column_name || '_legacy');
    execute format('alter table %I.%I rename column %I to %I',
                   rec.schema_name, rec.table_name, rec.column_name || '_bigint',
                   rec.column_name);
    execute format('alter table %I.%I drop column %I',
                   rec.schema_name, rec.table_name, rec.column_name || '_legacy');
  end loop;

  for rec in
    select * from migration_constraints
    where constraint_type <> 'f'
    order by case constraint_type when 'p' then 1 when 'u' then 2 else 3 end,
             schema_name, table_name
  loop
    execute format('alter table %I.%I add constraint %I %s',
                   rec.schema_name, rec.table_name, rec.constraint_name, rec.definition);
  end loop;
  for rec in select * from migration_constraints where constraint_type = 'f' order by schema_name, table_name loop
    execute format('alter table %I.%I add constraint %I %s',
                   rec.schema_name, rec.table_name, rec.constraint_name, rec.definition);
  end loop;
  for rec in select * from migration_indexes order by schema_name, index_name loop
    execute rec.definition;
  end loop;

  for rec in select * from migration_columns where is_row_id loop
    sequence_name := pg_get_serial_sequence(
      format('%I.%I', rec.schema_name, rec.table_name), 'id');
    if sequence_name is null then
      raise exception 'Identity sequence missing for %.%', rec.schema_name, rec.table_name;
    end if;
    execute format('select max(id) from %I.%I', rec.schema_name, rec.table_name) into max_id;
    perform setval(sequence_name::regclass, greatest(coalesce(max_id, 0), 1), max_id is not null);
  end loop;

  for rec in select * from migration_counts loop
    execute format('select count(*) from %I.%I', rec.schema_name, rec.table_name)
      into actual_count;
    if actual_count <> rec.row_count then
      raise exception 'Row count changed for %.%: % -> %',
        rec.schema_name, rec.table_name, rec.row_count, actual_count;
    end if;
  end loop;

  select count(*) into actual_count
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('control_plane', 'tenant_analyticalrx_dev')
    and c.relkind in ('r', 'p') and a.attnum > 0 and not a.attisdropped
    and (a.attname = 'id' or a.attname like '%_id' or a.attname = 'duplicate_of')
    and a.atttypid in ('uuid'::regtype, 'smallint'::regtype);
  if actual_count <> 0 then
    raise exception '% internal ID columns still have UUID/smallint type', actual_count;
  end if;

  select count(*) into actual_count from pg_constraint con
  join pg_class c on c.oid = con.conrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('control_plane', 'tenant_analyticalrx_dev')
    and con.contype in ('p', 'u', 'f', 'c');
  if actual_count <> (select count(*) from migration_constraints) then
    raise exception 'Constraint count changed: expected %, found %',
      (select count(*) from migration_constraints), actual_count;
  end if;

  raise notice 'Bigint migration validated; % columns converted, % constraints restored, % indexes restored',
    (select count(*) from migration_columns),
    (select count(*) from migration_constraints),
    (select count(*) from migration_indexes);
end
$$;

grant usage, select on all sequences in schema control_plane
  to analyticalrx_app_rw, analyticalrx_data_platform_password_rw;
grant usage, select on all sequences in schema tenant_analyticalrx_dev
  to analyticalrx_app_rw, analyticalrx_data_platform_password_rw;

\if :dry_run
rollback;
\echo Dry run rolled back successfully.
\else
commit;
\echo Bigint migration committed.
\endif
